#ifndef CPU_CONTROL_POLICY_BITS_H
#define CPU_CONTROL_POLICY_BITS_H

/* Integer expressions are shared by C and the 16/32-bit bootstrap assembler. */
#define CPU_CR0_PE 0x00000001
#define CPU_CR0_MP 0x00000002
#define CPU_CR0_ET 0x00000010
#define CPU_CR0_NE 0x00000020
#define CPU_CR0_WP 0x00010000
#define CPU_CR0_NW 0x20000000
#define CPU_CR0_CD 0x40000000
#define CPU_CR0_PG 0x80000000
#define CPU_CR0_PROTECTED (CPU_CR0_PE | CPU_CR0_MP | CPU_CR0_ET | CPU_CR0_NE | CPU_CR0_WP)
#define CPU_CR0_FINAL (CPU_CR0_PROTECTED | CPU_CR0_PG)
#define CPU_CR0_BOOTSTRAP (CPU_CR0_PROTECTED | CPU_CR0_CD)
#define CPU_CR4_PAE 0x20
#define CPU_CR4_PGE 0x80
#define CPU_CR4_FINAL CPU_CR4_PAE
#define CPU_EFER_LME 0x100
#define CPU_EFER_LMA 0x400
#define CPU_EFER_NXE 0x800
#define CPU_MSR_EFER 0xc0000080
#define CPU_MSR_PAT 0x277
#define CPU_FEATURE_MSR (1 << 5)
#define CPU_FEATURE_PAE (1 << 6)
#define CPU_FEATURE_PAT (1 << 16)
#define CPU_FEATURE_REQUIRED (CPU_FEATURE_MSR | CPU_FEATURE_PAE | CPU_FEATURE_PAT)
#define CPU_FEATURE_NX (1 << 20)
#define CPU_FEATURE_PAGE1G (1 << 26)
#define CPU_FEATURE_LM (1 << 29)
#define CPU_FEATURE_X2APIC (1 << 21)

#define CPU_PAT_UC 0
#define CPU_PAT_WC 1
#define CPU_PAT_WT 4
#define CPU_PAT_WP 5
#define CPU_PAT_WB 6
#define CPU_PAT_UCM 7
#define CPU_PAT_LOW (CPU_PAT_WB | (CPU_PAT_WT << 8) | (CPU_PAT_UCM << 16) | (CPU_PAT_UC << 24))
#define CPU_PAT_HIGH (CPU_PAT_WB | (CPU_PAT_WC << 8) | (CPU_PAT_UCM << 16) | (CPU_PAT_UC << 24))

#define CPU_BOOT_PENDING 0
#define CPU_BOOT_APPLIED 1
#define CPU_BOOT_NO_CPUID 2
#define CPU_BOOT_BASIC_FEATURE 3
#define CPU_BOOT_EXTENDED_FEATURE 4
#define CPU_BOOT_POLICY_MISMATCH 5
#define CPU_BOOT_X2APIC_FEATURE 6
#define CPU_BOOT_BAD_PARAMETERS 7
#define CPU_BOOT_READBACK 8
#define CPU_BOOT_PAGE_BYTES 4096
#define CPU_BOOT_STACK_RESERVE 256
#endif
